"""Identification of the 17 plane (wallpaper) groups.

Operations are given as (A, t): A a 2x2 integer matrix acting on fractional
coordinates of a 2D lattice basis, t a pair of `Fraction`s, so that
x' = A x + t. Any basis and origin is accepted; pure translations among the
operations are folded into the lattice, so conventional centred settings
work as well as primitive ones.
"""

from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from math import gcd

import numpy as np

from .integer_lattice import lattice_basis

PLANE_GROUP_SYMBOLS = (
    "p1",
    "p2",
    "pm",
    "pg",
    "cm",
    "p2mm",
    "p2mg",
    "p2gg",
    "c2mm",
    "p4",
    "p4mm",
    "p4gm",
    "p3",
    "p3m1",
    "p31m",
    "p6",
    "p6mm",
)

_LATTICE_OF_POINT_GROUP = {
    "1": "oblique",
    "2": "oblique",
    "m": "rectangular",
    "2mm": "rectangular",
    "4": "square",
    "4mm": "square",
    "3": "hexagonal",
    "3m": "hexagonal",
    "6": "hexagonal",
    "6mm": "hexagonal",
}


@dataclass(frozen=True)
class PlaneGroup:
    """A plane group type.

    Attributes:
        symbol: short Hermann-Mauguin symbol, e.g. "p4gm"
        number: International Tables (Vol. A) number, 1-17
        point_group: 2D point group symbol, e.g. "4mm"
        lattice: "oblique", "rectangular", "centred rectangular",
            "square" or "hexagonal"
    """

    symbol: str
    number: int
    point_group: str
    lattice: str

    def __str__(self):
        return self.symbol


def _as_op(rotation, translation):
    a = tuple(tuple(int(x) for x in row) for row in np.asarray(rotation))
    t = tuple(Fraction(x) % 1 for x in translation)
    return a, t


def _matmul(a, b):
    return tuple(
        tuple(sum(a[i][k] * b[k][j] for k in range(2)) for j in range(2))
        for i in range(2)
    )


def _matvec(a, v):
    return tuple(a[i][0] * v[0] + a[i][1] * v[1] for i in range(2))


def compose(op1, op2):
    "op1 after op2, translations reduced mod 1."
    (a1, t1), (a2, t2) = op1, op2
    t = _matvec(a1, t2)
    return _matmul(a1, a2), tuple((t[i] + t1[i]) % 1 for i in range(2))


def closure(generators):
    "The group (mod lattice translations) generated by 2D operations."
    identity = ((1, 0), (0, 1)), (Fraction(0), Fraction(0))
    ops = {identity}
    frontier = [_as_op(*g) for g in generators]
    while frontier:
        op = frontier.pop()
        if op in ops:
            continue
        ops.add(op)
        frontier.extend(compose(op, x) for x in list(ops))
        frontier.extend(compose(x, op) for x in list(ops))
    return list(ops)


def _inverse(m):
    det = m[0][0] * m[1][1] - m[0][1] * m[1][0]
    return [[m[1][1] / det, -m[0][1] / det], [-m[1][0] / det, m[0][0] / det]]


def _to_primitive(ops, metric):
    "Re-express ops and metric in a primitive basis of the full lattice."
    translations = [t for a, t in ops if a == ((1, 0), (0, 1))]
    rows = lattice_basis([(1, 0), (0, 1), *translations])
    b = [[rows[0][0], rows[1][0]], [rows[0][1], rows[1][1]]]
    b_inv = _inverse(b)
    new_ops = set()
    for a, t in ops:
        a_new = [
            [
                sum(b_inv[i][k] * a[k][l] * b[l][j] for k in range(2) for l in range(2))
                for j in range(2)
            ]
            for i in range(2)
        ]
        t_new = [sum(b_inv[i][k] * t[k] for k in range(2)) for i in range(2)]
        if any(x.denominator != 1 for row in a_new for x in row):
            raise ValueError("Operations are not compatible with their lattice")
        new_ops.add(_as_op([[int(x) for x in row] for row in a_new], t_new))
    b_float = np.array(b, dtype=float)
    return list(new_ops), b_float.T @ np.asarray(metric, dtype=float) @ b_float


def _primitive_vector(v):
    g = gcd(int(v[0]), int(v[1]))
    return (int(v[0]) // g, int(v[1]) // g)


def _eigenvector(a, sign):
    "Primitive integer vector v with A v = sign * v."
    m = [[a[0][0] - sign, a[0][1]], [a[1][0], a[1][1] - sign]]
    row = m[0] if any(m[0]) else m[1]
    return _primitive_vector((-row[1], row[0]))


def _point_group(rotations):
    proper = [a for a in rotations if _det(a) == 1]
    n_mirrors = len(rotations) - len(proper)
    order = len(proper)
    symbol = {1: "1", 2: "2", 3: "3", 4: "4", 6: "6"}[order]
    if n_mirrors == 0:
        return symbol
    if order == 1:
        return "m"
    return {"2": "2mm", "3": "3m", "4": "4mm", "6": "6mm"}[symbol]


def _det(a):
    return a[0][0] * a[1][1] - a[0][1] * a[1][0]


def _is_centred(mirror):
    "Whether the axis and normal of a mirror span a sublattice of index 2."
    e = _eigenvector(mirror, 1)
    f = _eigenvector(mirror, -1)
    return abs(e[0] * f[1] - e[1] * f[0]) == 2


def _has_true_mirror(a, t):
    """Whether (A, t + L) is a mirror (has fixed points) for some lattice L.

    The glide component (I + A)(t + L) / 2 lies along the axis e; it can be
    removed iff it is a multiple of the shortest such projection of L.
    """
    e = _eigenvector(a, 1)
    k = 0 if e[0] != 0 else 1

    def along_axis(v):
        w = _matvec(a, v)
        return Fraction(v[k] + w[k], 2) / e[k]

    glide = along_axis(t)
    step = Fraction(0)
    for basis_vector in ((1, 0), (0, 1)):
        c = along_axis(basis_vector)
        step = Fraction(
            gcd(step.numerator * c.denominator, c.numerator * step.denominator),
            step.denominator * c.denominator,
        )
    return (glide / step).denominator == 1


def identify_plane_group(operations, metric=None) -> PlaneGroup:
    """Identify the plane group type of a set of 2D operations.

    Args:
        operations: iterable of (rotation, translation) with rotation a 2x2
            integer matrix and translation two rationals; a complete set of
            coset representatives (plus any pure translations), or
            generators, in any basis and origin
        metric: 2x2 metric tensor of the basis; needed only to tell p3m1
            from p31m (defaults to the hexagonal metric of a 120 degree cell)

    Returns:
        PlaneGroup
    """
    ops = closure(operations)
    if metric is None:
        metric = np.array([[1.0, -0.5], [-0.5, 1.0]])
    ops, metric = _to_primitive(ops, metric)
    rotations = sorted({a for a, _ in ops})
    point_group = _point_group(rotations)
    mirrors = [(a, t) for a, t in ops if _det(a) == -1]
    symbol = _symbol(point_group, mirrors, metric)
    lattice = _LATTICE_OF_POINT_GROUP[point_group]
    if symbol[0] == "c":
        lattice = "centred rectangular"
    return PlaneGroup(
        symbol=symbol,
        number=PLANE_GROUP_SYMBOLS.index(symbol) + 1,
        point_group=point_group,
        lattice=lattice,
    )


def _symbol(point_group, mirrors, metric):
    if point_group in ("1", "2", "3", "4", "6"):
        return "p" + point_group
    if point_group == "6mm":
        return "p6mm"
    if point_group == "m":
        a, t = mirrors[0]
        if _is_centred(a):
            return "cm"
        return "pm" if _has_true_mirror(a, t) else "pg"
    if point_group == "2mm":
        if _is_centred(mirrors[0][0]):
            return "c2mm"
        n_true = sum(_has_true_mirror(a, t) for a, t in mirrors)
        return ("p2gg", "p2mg", "p2mm")[n_true]
    if point_group == "4mm":
        return "p4mm" if all(_has_true_mirror(a, t) for a, t in mirrors) else "p4gm"
    if point_group == "3m":
        e = np.array(_eigenvector(mirrors[0][0], 1), dtype=float)
        return "p31m" if e @ metric @ e < 1.5 * _shortest_norm(metric) else "p3m1"
    raise ValueError(f"Unknown 2D point group {point_group}")


def _shortest_norm(metric):
    "Squared length of the shortest lattice vector (Lagrange reduction)."
    a, b = np.array([1.0, 0.0]), np.array([0.0, 1.0])
    while True:
        if b @ metric @ b < a @ metric @ a:
            a, b = b, a
        mu = round((a @ metric @ b) / (a @ metric @ a))
        if mu == 0:
            return a @ metric @ a
        b = b - mu * a


def rational_origin(operations) -> np.ndarray:
    """An origin making the translations of 2D operations rational.

    The origin is placed on a centre of the highest-order rotation, or on a
    mirror or glide line when there is no rotation; relative to it, every
    translation is a rational multiple of the lattice vectors.

    Args:
        operations: (rotation, translation) pairs with float translations

    Returns:
        (2,) origin in fractional coordinates
    """
    ops = [
        (np.asarray(a, dtype=int), np.asarray(t, dtype=float)) for a, t in operations
    ]
    rotations = [
        (a, t)
        for a, t in ops
        if round(np.linalg.det(a)) == 1 and not np.array_equal(a, np.eye(2))
    ]
    if rotations:
        a, t = max(rotations, key=lambda op: _order(op[0]))
        return np.linalg.solve(np.eye(2) - a, t)
    mirrors = [(a, t) for a, t in ops if round(np.linalg.det(a)) == -1]
    if mirrors:
        a, t = mirrors[0]
        a_tuple = tuple(tuple(int(x) for x in row) for row in a)
        normal = np.array(_eigenvector(a_tuple, -1), dtype=float)
        axis = np.array(_eigenvector(a_tuple, 1), dtype=float)
        _, beta = np.linalg.solve(np.column_stack([axis, normal]), t)
        return 0.5 * beta * normal
    return np.zeros(2)


def _order(a) -> int:
    power, order = a.copy(), 1
    while not np.array_equal(power, np.eye(2, dtype=int)):
        power = power @ a
        order += 1
    return order
