"""
X-ray atomic scattering factors (form factors).

The atomic form factor f(s) describes how strongly an atom scatters X-rays as a
function of s = sin(theta) / lambda. It is the Fourier transform of the atomic
electron density: f(0) equals the number of electrons (~ the atomic number) and
falls off with increasing scattering angle.

We use the Waasmaier-Kirfel five-Gaussian parameterisation

    f(s) = sum_{i=1}^{5} a_i * exp(-b_i * s^2) + c

valid for s up to 6 A^-1.

Source: D. Waasmaier & A. Kirfel, Acta Cryst. (1995) A51, 416-431.
"""

