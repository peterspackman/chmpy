# atomic number -> coefficients, for fast lookup by Z
_COEFFICIENTS_BY_NUMBER = {
    Element[symbol].atomic_number: coeffs
    for symbol, coeffs in _FORM_FACTOR_COEFFICIENTS.items()
}

#: atomic numbers with tabulated scattering factors
AVAILABLE = frozenset(_COEFFICIENTS_BY_NUMBER)


def atomic_form_factor(atomic_numbers, sin_theta_over_lambda) -> np.ndarray:
    """Evaluate atomic form factors f(s) (Waasmaier-Kirfel five-Gaussian fit).

    Args:
        atomic_numbers: (N,) array of integer atomic numbers
        sin_theta_over_lambda: (M,) array of s = sin(theta)/lambda values in A^-1

    Returns:
        (N, M) array where entry (i, j) is f of atom i at s value j.

    Raises:
        ValueError: if an atomic number has no tabulated coefficients. The set
            of supported atomic numbers is available as `AVAILABLE`.
    """
    atomic_numbers = np.atleast_1d(np.asarray(atomic_numbers, dtype=int))
    s = np.atleast_1d(np.asarray(sin_theta_over_lambda, dtype=np.float64))
    s2 = s * s

    result = np.empty((len(atomic_numbers), len(s)), dtype=np.float64)
    for i, z in enumerate(atomic_numbers):
        if int(z) not in _COEFFICIENTS_BY_NUMBER:
            raise ValueError(
                f"No tabulated X-ray scattering factor for "
                f"{Element.from_atomic_number(int(z))} (atomic number {int(z)})"
            )
        a_coeffs, b_coeffs, c = _COEFFICIENTS_BY_NUMBER[int(z)]
        f = np.full_like(s, c)
        for a_k, b_k in zip(a_coeffs, b_coeffs, strict=True):
            f += a_k * np.exp(-b_k * s2)
        result[i] = f
    return result
